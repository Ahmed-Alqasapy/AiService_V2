        /// <summary>
        /// Fixes stuck or broken Arabic words in the input text using the predefined dictionary.
        /// Applies fixes in descending order of key length for better matching (longer phrases first).
        /// </summary>
        /// <param name="text">Input Arabic text with possible OCR artifacts</param>
        /// <returns>Cleaned and corrected Arabic text</returns>
        public static string FixStuckWords(string text)
        {
            if (string.IsNullOrWhiteSpace(text))
                return text;

            // Sort keys by length descending to match longer phrases first (e.g., "المعل ومات" before "معل ومات")
            var sortedPairs = StuckWords
                .OrderByDescending(kvp => kvp.Key.Length)
                .ThenByDescending(kvp => kvp.Key); // Secondary sort for consistency

            foreach (var pair in sortedPairs)
            {
                // Escape special regex chars if needed, but our keys are mostly Arabic letters/spaces
                string pattern = Regex.Escape(pair.Key);
                // Replace whole word matches only to avoid partial overlaps
                text = Regex.Replace(text, $@"\b{pattern}\b", pair.Value);
            }

            return text;
        }

        /// <summary>
        /// Aggressive version: Also fixes without word boundaries (useful for very broken text)
        /// Use carefully — may over-correct in rare cases
        /// </summary>
        public static string FixStuckWordsAggressive(string text)
        {
            if (string.IsNullOrWhiteSpace(text))
                return text;

            var sortedPairs = StuckWords
                .OrderByDescending(kvp => kvp.Key.Length);

            foreach (var pair in sortedPairs)
            {
                string escaped = Regex.Escape(pair.Key);
                text = Regex.Replace(text, escaped, pair.Value);
            }

            return text;
        }
