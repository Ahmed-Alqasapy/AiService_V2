-- AI Admin Dashboard schema. Run against the dev Oracle DB (schema APP_AML) before
-- starting the API: MyDbContext.Admin.cs maps directly onto these tables/sequences.
-- Not run automatically -- review and execute by hand (see CLAUDE.md: this DB is shared).

CREATE SEQUENCE APP_AML.AI_CHAT_LOG_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE TABLE APP_AML.AI_CHAT_LOG (
    LOG_ID          NUMBER          DEFAULT APP_AML.AI_CHAT_LOG_SEQ.NEXTVAL PRIMARY KEY,
    CREATED_ON      TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
    USER_ID         VARCHAR2(50),
    CHANNEL         VARCHAR2(10),            -- 'text' | 'voice'
    QUESTION        NVARCHAR2(2000) NOT NULL,
    QUESTION_NORM   NVARCHAR2(2000),
    QUESTION_HASH   VARCHAR2(64),
    INTENT          VARCHAR2(50),
    ANSWER_STATUS   VARCHAR2(20)    NOT NULL,
    ANSWER          NCLOB,
    TOP_SCORE       NUMBER(8,5),
    FILE_HITS       NUMBER(5),
    DB_HITS         NUMBER(5),
    SOURCES_JSON    NCLOB,
    MODEL           VARCHAR2(60),
    INPUT_TOKENS    NUMBER(10)      DEFAULT 0,
    OUTPUT_TOKENS   NUMBER(10)      DEFAULT 0,
    COST_USD        NUMBER(12,6)    DEFAULT 0,
    SEARCH_MS       NUMBER(10),
    LLM_MS          NUMBER(10),
    TOTAL_MS        NUMBER(10),
    ERROR_MSG       NVARCHAR2(1000)
);

CREATE INDEX APP_AML.IX_AI_CHAT_LOG_DATE   ON APP_AML.AI_CHAT_LOG (CREATED_ON);
CREATE INDEX APP_AML.IX_AI_CHAT_LOG_STATUS ON APP_AML.AI_CHAT_LOG (ANSWER_STATUS, QUESTION_HASH);

CREATE SEQUENCE APP_AML.AI_INDEXED_FILE_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE TABLE APP_AML.AI_INDEXED_FILE (
    FILE_ID        NUMBER          DEFAULT APP_AML.AI_INDEXED_FILE_SEQ.NEXTVAL PRIMARY KEY,
    FILE_NAME      NVARCHAR2(400)  NOT NULL,
    FILE_SIZE      NUMBER(15),
    UPLOADED_BY    VARCHAR2(50),
    UPLOADED_ON    TIMESTAMP       DEFAULT SYSTIMESTAMP,
    STATUS         VARCHAR2(20)    NOT NULL,  -- Queued | Indexing | Indexed | Failed | Skipped
    COLLECTION     VARCHAR2(100),
    CHUNK_COUNT    NUMBER(10),
    PAGE_COUNT     NUMBER(10),
    DURATION_MS    NUMBER(10),
    ERROR_MSG      NVARCHAR2(2000),
    INDEXED_ON     TIMESTAMP
);
CREATE INDEX APP_AML.IX_AI_INDEXED_FILE_NAME ON APP_AML.AI_INDEXED_FILE (FILE_NAME);
