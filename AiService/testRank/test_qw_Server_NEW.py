# الـ URL الرسمي للسيرفر الحكومي
url = "http://10.21.2.143:8000/rerank"
headers = {"Content-Type": "application/json; charset=utf-8"}

def test(query, passages, title):
    payload = {
        "query": query,
        "passages": passages,
        "top_k": len(passages)
    }
   
    try:
        r = requests.post(url, json=payload, headers=headers, timeout=300)  # timeout أعلى للنصوص الكاملة الطويلة
        r.raise_for_status()
        r.encoding = "utf-8"
        res = r.json()
    except requests.exceptions.HTTPError as e:
        error_detail = e.response.text[:800] if e.response.text else "No response body"
        return f"خطأ HTTP {e.response.status_code}: {error_detail}"
    except Exception as e:
        return f"خطأ في الاتصال: {str(e)}"
   
    out = []
    out.append("="*130)
    out.append(f"SUCCESS {title}")
    out.append(f"السؤال: {query}")
    out.append(f"الوقت: {datetime.now().strftime('%Y-%%م-%d %H:%M:%S')}")
    out.append(f"عدد النتائج: {len(passages)} passages (نصوص كاملة بدون اقتطاع)")
    out.append("-"*130)
    out.append(f"{'رت':<6} {'الدرجة':<18} النص (معاينة أول 200 حرف)")
    out.append("-"*130)
   
    for item in res.get("results", []):
        score = item.get("relevance_score") or item.get("score", 0)
        text_preview = item['text'][:200].replace("\n", " ") + "..." if len(item['text']) > 200 else item['text']
        out.append(f"{item['rank']:<6} {score:<18.10f} {text_preview}")
   
    out.append("\n")
    return "\n".join(out)

