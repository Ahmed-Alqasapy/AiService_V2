#Test File which is Qwen_try_one.py using model qwen3-reranker-.6B
url = "http://127.0.0.1:8000/rerank"
headers = {"Content-Type": "application/json; charset=utf-8"}

def test(query, passages, title):
    payload = {"query": query, "passages": passages, "top_k": len(passages)}
    r = requests.post(url, json=payload, headers=headers)
    r.encoding = "utf-8"
    res = r.json()
    
    out = []
    out.append("="*100)
    out.append(title)
    out.append(f"السؤال: {query}")
    out.append(f"الوقت: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}")
    out.append("-"*100)
    out.append(f"{'رت':<4} {'الدرجة':<12} النص")
    out.append("-"*100)
    for x in res["results"]:
        out.append(f"{x['rank']:<4} {x['relevance_score']:<12.6f} {x['text']}")
    out.append("\n")
    return "\n".join(out)

